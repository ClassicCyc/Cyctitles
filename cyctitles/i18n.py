"""Tiny translation layer for the UI (English + Russian).

``tr("key", **kw)`` looks up the string for the current language, falling back
to English. Unknown keys return a humanised version of the key itself so a
missing translation never crashes the app. Change the language at runtime with
:func:`set_language`; the app then rebuilds its visible text.
"""

from __future__ import annotations

from .config import load_config

# Languages the UI itself can be displayed in (not the spoken languages).
UI_LANGUAGES = [
    ("English", "en"),
    ("Русский", "ru"),
    ("Українська", "uk"),
    ("Français", "fr"),
    ("Español", "es"),
    ("Deutsch", "de"),
    ("中文", "zh"),
    ("日本語", "ja"),
]

_current = "en"


def set_language(code: str) -> None:
    global _current
    _current = code if code in _STRINGS else "en"


def current_language() -> str:
    return _current


def init_from_config() -> None:
    """Read the saved UI language (call once at startup)."""
    try:
        cfg = load_config()
        set_language(getattr(cfg, "ui_language", "en"))
    except Exception:  # noqa: BLE001
        set_language("en")


def tr(key: str, **kw: object) -> str:
    lang = _STRINGS.get(_current, _STRINGS["en"])
    template = lang.get(key) or _STRINGS["en"].get(key) or key.replace("_", " ").capitalize()
    try:
        return template.format(**kw) if kw else template
    except (KeyError, IndexError):
        return template


